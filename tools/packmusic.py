"""
packmusic.py - the front end's tunes packed for the disc (step 2 layer 4).

    python tools/packmusic.py [src/music.6502] [src/music_packed.6502]

Reads the title and high score tunes (src/music.6502: the EQUB bytes from .title_screen_music_data
to the end, 3,968 bytes, &9300-&A27F in bank 5), packs them with ZX02 (tools/zx02.py, the kit's,
default mode), checks that the stream unpacks to the same bytes, and writes them as EQUBs with
MUSIC_SIZE. src/game.6502's unpack_for_play unpacks them over bank 5's music area at start-up
(src/lib/zx02depack.6502); the area itself carries other data on the disc (src/bank5.6502).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import zx02  # noqa: E402

BS, NL = chr(92), chr(10)


def music_bytes(path):
    out, on = [], False
    for ln in Path(path).read_text(encoding="utf-8").split(NL):
        if ln.startswith(".title_screen_music_data"):
            on = True
        s = ln.split(BS)[0].strip()
        if on and s.startswith("EQUB"):
            out += [int(v.strip()[1:], 16) for v in s[4:].split(",")]
    return bytes(out)


def main(src="src/music.6502", out="src/music_packed.6502"):
    raw = music_bytes(src)
    assert len(raw) == 0xF80, len(raw)
    packed = zx02.compress(raw)
    assert zx02.decompress(packed) == raw, "the stream does not unpack to the tunes"
    c = BS + " "
    lines = [c + "music_packed.6502 - GENERATED by tools/packmusic.py from src/music.6502; do not edit.",
             c + f"The front end's tunes, {len(raw)} bytes, packed with ZX02 to {len(packed)}: unpacked to",
             c + "title_screen_music_data at start-up (src/game.6502 unpack_for_play).",
             f"MUSIC_SIZE = &{len(raw):X}",
             ".music_packed"]
    for k in range(0, len(packed), 16):
        lines.append("    EQUB " + ", ".join(f"&{v:02X}" for v in packed[k:k + 16]))
    Path(out).write_text(NL.join(lines) + NL)
    print(f"wrote {out}: {len(raw)} bytes packed to {len(packed)}")


if __name__ == "__main__":
    main(*sys.argv[1:])
