"""
scrolltext.py - the title screen's scroll text, from an editable text file into the build.

    python tools/scrolltext.py [src/scrolltext.txt] [build/scrolltext.6502]

build.ps1 and the Makefile run it before every assembly; src/bank5.6502 INCLUDEs what it writes
(`scrolltext_text` .. `scrolltext_end`, then the original's &FF after it). The text file:

  - lines starting with # are comments; blank lines are skipped;
  - every other line is stripped and the lines are joined with one space, then GAP spaces are
    added at the end (the gap before the text comes round again: the original's 4);
  - lower case is taken as upper case; the title font has A-Z, 0-9, space and . , / : = and
    the copyright symbol, written (C). Anything else stops the build, naming the line.

The original's text rebuilds the original's bytes (the step 1 reference): the font codes are its
own (0-9 &00-&09, A-Z &0A-&23, = &24, (C) &26, space &25, . &27, : &2F, , &31, / &32).
"""
import sys
from pathlib import Path

GAP = 4
CODES = {**{chr(48 + i): i for i in range(10)}, **{chr(65 + i): 10 + i for i in range(26)},
         "=": 0x24, " ": 0x25, ".": 0x27, ":": 0x2F, ",": 0x31, "/": 0x32}
COPYRIGHT = 0x26
BS = chr(92)


def encode(path):
    words = []
    for n, line in enumerate(Path(path).read_text(encoding="utf-8").splitlines(), 1):
        if line.lstrip().startswith("#") or not line.strip():
            continue
        words.append((n, line.strip().upper()))
    text, codes = "", []
    for k, (n, line) in enumerate(words):
        if k:
            text += " "
            codes.append(CODES[" "])
        i = 0
        while i < len(line):
            if line.startswith("(C)", i):
                text += "@"                 # one character a code, so the comments line up
                codes.append(COPYRIGHT)
                i += 3
                continue
            c = line[i]
            if c not in CODES:
                sys.exit(f"{path}:{n}: {c!r} is not in the title font (A-Z, 0-9, space, . , / : = and (C))")
            text += c
            codes.append(CODES[c])
            i += 1
    text += " " * GAP
    codes += [CODES[" "]] * GAP
    return text, codes


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "src/scrolltext.txt"
    out = Path(sys.argv[2] if len(sys.argv) > 2 else "build/scrolltext.6502")
    text, codes = encode(src)
    lines = [f"{BS} scrolltext.6502 - GENERATED by tools/scrolltext.py from {src} at every build: edit that, not this.",
             f"{BS} The title's scroll text in the title font's codes: {len(codes)} characters, then the original's &FF.",
             ".scrolltext_text"]
    for i in range(0, len(codes), 16):
        chunk = codes[i:i + 16]
        lines.append("    EQUB " + ", ".join(f"&{c:02X}" for c in chunk) + f"    {BS} \"{text[i:i + 16]}\"")
    lines += [".scrolltext_end", "    EQUB &FF", ""]
    new = "\n".join(lines)
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text(encoding="utf-8") != new:     # unchanged: the file's time kept (make)
        out.write_text(new, encoding="utf-8")


if __name__ == "__main__":
    main()
