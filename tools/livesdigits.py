"""livesdigits.py - the lives digit as plot_lives leaves it on screen, for each count: the
renderer writes these bytes instead of plotting the character pixel by pixel (layer 3, D).

    python tools/livesdigits.py src/font.6502 src/lives_digits.6502

plot_lives draws font character lives * 6 + &6C (the digits from "0") at the screen start:
each of the character's 6 columns is a pixel of a MODE 2 byte, left then right, so 3 bytes
across; a pixel whose font bit is set becomes &3C AND that pixel's mask, any other 0, and both
pixels of each byte are written, so the bytes do not depend on what was there. Row Y of the
cell is bit Y of the column's font byte. Then a 4th byte column of 0. 32 bytes a count, as
4 columns of 8 rows; counts 0-15 (the font offset wraps as the game's 8-bit sum does).
"""
import re
import sys
from pathlib import Path

BS = chr(92)
src, out = sys.argv[1:3]
font = []
for line in Path(src).read_text().splitlines():
    m = re.match(r"\s*EQUB\s+([^" + BS + BS + r"]*)", line)
    if m:
        font += [int(x.strip()[1:], 16) for x in m.group(1).split(",") if x.strip()]
lines = [BS + " lives_digits.6502 - GENERATED by tools/livesdigits.py from font.6502; do not edit.",
         BS + " The lives digit's bytes for each count 0-15, 4 columns of 8 rows (the 4th blank).",
         ".lives_digits"]
# decision 46: with GAMEPLAY_OPTIONS, entry 10 is infinite lives' glyph (OPT_INFINITE), two loops
INFINITY = ["......", "......", ".#..#.", "#.##.#", "#.##.#", ".#..#.", "......", "......"]
for lives in range(16):
    if lives == 10:
        cols = []
        for bx in range(3):
            cols.append([(0x28 if INFINITY[y][2 * bx] == "#" else 0) | (0x14 if INFINITY[y][2 * bx + 1] == "#" else 0) for y in range(8)])
        cols.append([0] * 8)
        lines.append("IF GAMEPLAY_OPTIONS")
        lines.append("    EQUB " + ", ".join(f"&{b:02X}" for c in cols for b in c) + f"    {BS} 10: infinite lives (decision 46)")
        lines.append("ELSE")
    off = (lives * 6 + 0x6C) & 0xFF
    cols = []
    for bx in range(3):
        left, right = font[off + 2 * bx] if off + 2 * bx < len(font) else 0, font[off + 2 * bx + 1] if off + 2 * bx + 1 < len(font) else 0
        cols.append([(0x28 if left >> y & 1 else 0) | (0x14 if right >> y & 1 else 0) for y in range(8)])
    cols.append([0] * 8)
    lines.append("    EQUB " + ", ".join(f"&{b:02X}" for c in cols for b in c) + f"    {BS} {lives}")
    if lives == 10:
        lines.append("ENDIF")
        lines.append("IF GAMEPLAY_SHIELD = 0   " + BS + " 11-15: never shown; GAMEPLAY_SHIELD's renderer copies the HUD, and wants the room")
lines.append("ENDIF")
Path(out).write_text("\n".join(lines) + "\n")
print(f"wrote {out}: font {len(font)} bytes")
